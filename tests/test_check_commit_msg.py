"""commit-msg hook rejects AI attribution and keeps human co-authors."""

import importlib.util
from pathlib import Path

import pytest

SCRIPT = Path(__file__).parents[1] / "scripts/check-commit-msg.py"
spec = importlib.util.spec_from_file_location("check_commit_msg", SCRIPT)
check = importlib.util.module_from_spec(spec)
spec.loader.exec_module(check)


@pytest.mark.parametrize(
    "line",
    [
        "Co-authored-by: Claude <noreply@anthropic.com>",
        "Co-authored-by: Claude Opus 4 <a@b.c>",
        "Co-authored-by: GitHub Copilot <a@b.c>",
        "Co-authored-by: Someone <123+copilot@users.noreply.github.com>",
        "Generated with [Claude Code](https://claude.com/claude-code)",
        "co-authored-by: CODEX <x@y.z>",
        "Co-Authored-By: Someone <bot@openai.com>",
        "Co-authored-by: Copilot <copilot@github.com>",
        "Co-authored-by: Cursor Agent <a@b.c>",
        "Co-authored-by: Gemini <a@b.c>",
        "Co-authored-by: aider (gpt) <a@b.c>",
        "Co-authored-by: Devin AI <a@b.c>",
        "Co-authored-by: ChatGPT <a@b.c>",
        "Generated with Claude Code",
        "\U0001f916 Generated by ChatGPT",
    ],
)
def test_rejects_ai_attribution(line):
    assert check.violations(f"feat: x\n\nbody\n\n{line}\n")


@pytest.mark.parametrize(
    "msg",
    [
        "feat: x\n\nCo-authored-by: Jane Doe <jane@example.com>\n",
        "feat: x\n\nCo-authored-by: Devin Smith <devin@example.com>\n",
        "feat: x\n\nCo-authored-by: Gemini X <x@example.com>\n",
        "feat: configure Claude plugins\n\nGenerated code is checked; Claude plugins documented.\n",
        "docs: mention generated with care in prose\n",
        "fix: claude is a name in a body line\n",
    ],
)
def test_allows_human_messages(msg):
    assert not check.violations(msg)


def test_main_exit_codes(tmp_path):
    bad = tmp_path / "bad"
    bad.write_text("x\n\nCo-authored-by: Claude <a@b.c>\n")
    good = tmp_path / "good"
    good.write_text("x\n\nCo-authored-by: Jane <j@example.com>\n")
    assert check.main([str(bad)]) == 1
    assert check.main([str(good)]) == 0
